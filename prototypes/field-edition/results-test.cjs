const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const {JSDOM,VirtualConsole}=require('../../tools/node_modules/jsdom');
const built=process.argv[2];
const files=built?path.resolve(built):__dirname, shell=built?'index.html':'live-preview.html';
const html=fs.readFileSync(path.join(files,shell),'utf8');
const js=[...html.matchAll(/<script(?: defer)? src="([^"?]+)(?:\?[^"]*)?"/g)].map(x=>x[1]);
const tick=()=>new Promise(r=>setTimeout(r,25));
const pending=[];
const w=new JSDOM(html,{url:'https://monitor.example/?lang=en#today',runScripts:'outside-only',virtualConsole:new VirtualConsole()}).window;
const d=w.document,q=s=>d.querySelector(s),all=s=>[...d.querySelectorAll(s)];
w.addEventListener('error',e=>pending.push(e.error));
w.fetch=async u=>{const url=new URL(u,'https://monitor.example/');assert.equal(url.origin,'https://monitor.example');let f=path.join(files,u.split('?')[0]);if(!fs.existsSync(f))return {ok:false,status:404};return {ok:true,json:async()=>JSON.parse(fs.readFileSync(f,'utf8')),text:async()=>fs.readFileSync(f,'utf8')}};
const navigate=async hash=>{w.location.hash=hash;await tick()};
const navTabs=()=>all('header [data-tab]');
const mainRoute=key=>all('header [data-tab][aria-current="page"]').map(a=>a.dataset.tab).join()===key;
const language=async key=>{q('#language').value=key;q('#language').dispatchEvent(new w.Event('change'));await tick()};
(async()=>{
  w.eval(js.map(f=>fs.readFileSync(path.join(files,f),'utf8')).join('\n'));
  await tick();
  const base='#results', old='#texts/results';
  assert.deepEqual(navTabs().map(a=>a.dataset.tab),['today','results','texts','pulse','explore']);
  assert.deepEqual(navTabs().map(a=>a.textContent),['Today','Results','Texts','Pulse','Explore']);
  assert(mainRoute('today'));
  assert(q('#results-today').textContent.includes('COP31 ended without an overarching agreement.'));
  assert(q('#results-today').compareDocumentPosition(q('.edition-grid')) & w.Node.DOCUMENT_POSITION_FOLLOWING);
  assert.equal(q('#results-today a').getAttribute('href'),base);
  assert.equal(q('#results-texts a').getAttribute('href'),base);
  assert(!q('#today').hidden);
  q('[data-tab=results]').click();
  await tick();
  assert.equal(w.location.hash,base);
  assert(!q('#results').hidden&&q('#texts').hidden&&q('#today').hidden);
  assert(mainRoute('results'));
  assert.equal(d.activeElement.id,'results-heading');
  assert.equal(q('#results-heading').textContent,'COP31 Results');
  const {outcomes,milestones}=w.COP31_RESULTS_DATA;
  assert(outcomes.length>0);
  assert.equal(all('.result-card').length,outcomes.length);
  assert.deepEqual(all('.result-card .result-status').map(n=>n.textContent),Array.from(outcomes,o=>o.status==='adopted'?'Adopted':'Not adopted'));
  const okSource=s=>{const u=new URL(s);return u.protocol==='https:'&&!u.username&&!u.password&&!u.port&&['unfccc.int','enb.iisd.org'].includes(u.hostname)};
  assert(all('.result-card .result-source').every(a=>okSource(a.href)));
  assert.equal(new Set(outcomes.map(o=>o.id)).size,outcomes.length);
  for(const o of outcomes){
    assert(/^[a-z][a-z0-9-]{1,50}$/.test(o.id));
    assert.deepEqual(Object.keys(o).sort(),['body','en','id','pt','source','stage','status','topic']);
    assert(o.en.length===3&&o.pt.length===3&&okSource(o.source));
    assert.equal(o.stage==='auv',o.status==='adopted');
    await navigate(base+'/decision/'+o.id);
    assert.equal(q('#results-heading').textContent,o.en[0]);
    assert.equal(q('.result-provenance a').href,o.source);
    assert.equal(q('.result-provenance details').open,false);
    assert(!q('#results').textContent.includes('undefined'));
  }
  await navigate(old);
  assert.equal(w.location.hash,base);
  assert(mainRoute('results'));
  assert.equal(all('.result-card').length,outcomes.length);
  const pact=outcomes.find(o=>o.id==='antalya-pact');assert(pact);
  await navigate(old+'/decision/antalya-pact');
  assert.equal(w.location.hash,base+'/decision/antalya-pact');
  assert.equal(q('#results-heading').textContent,pact.en[0]);
  await navigate(old+'/decision/mitigation');
  assert.equal(w.location.hash,base+'/decision/mitigation');
  assert(mainRoute('results'));
  assert.equal(q('.result-stage').textContent,'Text available: No adopted text');
  assert(q('.result-steps').textContent.includes('CMA 9'));
  await navigate(old+'/next');
  assert.equal(w.location.hash,base+'/next');
  assert(mainRoute('results'));
  assert.equal(all('.result-steps li').length,milestones.length);
  assert(all('.result-steps time').some(x=>x.dateTime==='2027-08'&&x.textContent.startsWith('By ')));
  const sel=q('.result-filter select');sel.value='adaptation';sel.dispatchEvent(new w.Event('change'));
  const adaptationIDs=new Set(outcomes.filter(o=>o.topic==='adaptation').map(o=>o.id));
  const adaptationMilestones=milestones.filter(m=>adaptationIDs.has(m.id));
  assert(adaptationMilestones.length>0);
  assert.equal(all('.result-steps li').length,adaptationMilestones.length);
  assert.deepEqual(all('.result-steps li a').map(a=>a.hash),Array.from(adaptationMilestones,m=>base+'/decision/'+m.id));
  const localizedNav={en:'Results',pt:'Resultados',es:'Resultados',fr:'Résultats',ru:'Итоги',zh:'成果',ar:'النتائج'};
  for(const key of Object.keys(localizedNav)){
    await language(key);
    assert.equal(q('[data-tab=results]').textContent,localizedNav[key]);
    assert.equal(q('#results-today [aria-labelledby=results-today-heading] p').lang,'');
    assert.equal(q('#results-today p').textContent.startsWith('COP31 ended'),key==='en');
    assert(navTabs().every(a=>a.textContent&&!a.textContent.includes('undefined')));
    assert.equal(d.documentElement.lang,key);
    assert.equal(d.documentElement.dir,key==='ar'?'rtl':'ltr');
    await navigate(base+'/decision/adaptation');
    const h=q('#results-heading');
    assert.equal(h.lang,key==='pt'?'pt':'en');
    assert.equal(h.dir,'ltr');
    assert(h.textContent.length>10&&!q('#results').textContent.includes('undefined'));
    await navigate(base+'/next');
  }
  await navigate(base+'/decision/unknown');
  assert.equal(all('.result-card').length,outcomes.length);
  await navigate('#texts');
  assert(!q('#texts').hidden&&q('#results').hidden);
  assert(mainRoute('texts'));
  await navigate('#today');
  assert(!q('#today').hidden);
  await navigate('#main');
  assert.equal(d.activeElement.id,'main');
  assert.deepEqual(pending,[]);
  console.log('PASS: Results navigation, public records, canonical and legacy deep links, dates, filtering, keyboard focus, all seven locale shells, Arabic RTL and navigation regressions');
})().catch(e=>{console.error(e);process.exitCode=1}).finally(()=>w.close());
